// values renders values.yaml, defaulting the images to the release the
// installer pins.
func values() string {
	var b bytes.Buffer
	fmt.Fprintf(&b, `# The Substrate version: the ate.dev/substrate-version label the atelet
# DaemonSet and WorkerPools select nodes by, which the caller puts on the
# nodes. For pre-built images, the image tag without any @digest.
substrateVersion: %q

# Control-plane images, by the name upstream publishes them under.
images:
`, snapshot.ReleaseVersion)
	names := append([]string(nil), Images...)
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "  %s: %q\n", n, snapshot.ReleaseRepo+"/"+n+":"+snapshot.ReleaseVersion)
	}
	b.WriteString(`
# The issuer of the cluster's service-account tokens, which ate-api-server
# accepts for actor identity. On GKE:
# https://container.googleapis.com/v1/projects/PROJECT/locations/LOCATION/clusters/CLUSTER
jwtIssuer: ""

# GKE Managed Prometheus scraping of atenet-router's envoy.
podMonitoring: true

# The key pools (see templates/key-pools.yaml), generated by the caller.
# CA pools: pool (the pool JSON), cert (PEM root), key (PEM PKCS#8).
# JWT pool: pool only.
keyPools:
`)
	for _, p := range KeyPools {
		if p.JWT {
			fmt.Fprintf(&b, "  %s:\n    pool: \"\"\n", p.Key)
		} else {
			fmt.Fprintf(&b, "  %s:\n    pool: \"\"\n    cert: \"\"\n    key: \"\"\n", p.Key)
		}
	}
	return b.String()
}

// escape makes text safe to put in a Helm template verbatim.
func escape(s string) string {
	s = strings.ReplaceAll(s, "{{", "\x00OPEN\x00")
	s = strings.ReplaceAll(s, "}}", `{{ "}}" }}`)
	return strings.ReplaceAll(s, "\x00OPEN\x00", `{{ "{{" }}`)
}

// dropDocs removes the YAML documents of the given kinds.
func dropDocs(src string, kinds []string) string {
	if len(kinds) == 0 {
		return src
	}
	docs := regexp.MustCompile(`(?m)^---[ \t]*$`).Split(src, -1)
	var keep []string
	for _, d := range docs {
		drop := false
		for _, k := range kinds {
			if regexp.MustCompile(`(?m)^kind:\s*` + regexp.QuoteMeta(k) + `\s*$`).MatchString(d) {
				drop = true
			}
		}
		if !drop {
			keep = append(keep, d)
		}
	}
	return strings.Join(keep, "---")
}
