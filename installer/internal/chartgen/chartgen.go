// credentialProviderPolicy keeps an operator's edits: ate-setup creates this
// ConfigMap only when it is absent, so the chart reuses what is there.
func (g *generator) credentialProviderPolicy() string {
	src := g.read("manifests/egress-credential-injection/namespace-policy.yaml")
	const key = "  namespace-policy.yaml: |\n"
	i := strings.Index(src, key)
	if i < 0 {
		g.fail("namespace-policy.yaml: no namespace-policy.yaml key")
		return ""
	}
	head, body := escape(src[:i]), src[i+len(key):]
	return head + `{{- $existing := lookup "v1" "ConfigMap" "ate-system" "k8s-credential-provider-namespace-policy" }}
{{- if and $existing $existing.data }}
{{ toYaml $existing.data | indent 2 }}
{{- else }}
` + key + escape(body) + "{{- end }}\n"
}

func keyPoolsTemplate() string {
	var b strings.Builder
	b.WriteString(`# The key pools ate-setup generates (steps/create.go). They are values so the
# caller generates them once and keeps them: regenerating a CA rotates it out
# from under every certificate it issued.
`)
	for i, p := range KeyPools {
		if i > 0 {
			b.WriteString("---\n")
		}
		v := ".Values.keyPools." + p.Key
		if p.JWT {
			fmt.Fprintf(&b, `apiVersion: v1
kind: Secret
metadata:
  name: %s
  namespace: %s
type: Opaque
data:
  pool: {{ required "%s.pool is required" %s.pool | b64enc }}
`, p.Name, p.Namespace, v[len(".Values."):], v)
			continue
		}
		fmt.Fprintf(&b, `apiVersion: v1
kind: Secret
metadata:
  name: %[1]s
  namespace: %[2]s
type: kubernetes.io/tls
data:
  pool: {{ required "%[3]s.pool is required" %[4]s.pool | b64enc }}
  tls.crt: {{ required "%[3]s.cert is required" %[4]s.cert | b64enc }}
  tls.key: {{ required "%[3]s.key is required" %[4]s.key | b64enc }}
`, p.Name, p.Namespace, v[len(".Values."):], v)
		if p.Key == "actorIdCA" {
			fmt.Fprintf(&b, `---
# The actor-id CA's root, for atenet-egress.
apiVersion: v1
kind: Secret
metadata:
  name: actor-id-ca-certs
  namespace: ate-system
type: Opaque
data:
  ca.crt: {{ %s.cert | b64enc }}
`, v)
		}
	}
	return b.String()
}

