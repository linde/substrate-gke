func (g *generator) mainChart(dir string) {
	defer g.stamp(dir, "substrate", "Agent Substrate's control plane, as `ate-setup deploy ate-system` installs it with pre-built images. Install into ate-system, after substrate-crds.")
	g.yaml(path.Join(dir, "values.yaml"), values())
	g.yaml(path.Join(dir, "templates/_helpers.tpl"), helpers)
	for i, m := range manifests {
		body := g.transform(m)
		name := fmt.Sprintf("%02d-%s", i+1, strings.TrimSuffix(path.Base(m.src), ".tmpl"))
		g.yaml(path.Join(dir, "templates", name), body)
	}
	g.yaml(path.Join(dir, "templates/key-pools.yaml"), keyPoolsTemplate())
	g.yaml(path.Join(dir, "templates/api-server-config.yaml"), apiServerConfig)
	g.yaml(path.Join(dir, "templates/credential-provider-policy.yaml"), g.credentialProviderPolicy())
	g.yaml(path.Join(dir, "templates/postgres-setup.yaml"), postgresSetupConfigMap)
	g.files[path.Join(dir, "files/setup.sql")] = []byte(g.read("pkg/postgressetup/setup.sql"))
}

var koRef = regexp.MustCompile(`ko://github\.com/agent-substrate/substrate/cmd/([A-Za-z0-9/_-]+)`)

// transform applies ate-setup's substitutions to one upstream file.
func (g *generator) transform(m manifest) string {
	src := g.read(m.src)
	if g.err != nil {
		return ""
	}
	src = dropDocs(src, m.drop)
	src = escape(src)

	known := map[string]bool{}
	for _, name := range Images {
		known[name] = true
	}
	src = koRef.ReplaceAllStringFunc(src, func(ref string) string {
		name := path.Base(koRef.FindStringSubmatch(ref)[1])
		if !known[name] {
			g.fail("%s: image %s is not one the chart takes (chartgen.Images)", m.src, ref)
		}
		return fmt.Sprintf(`{{ index .Values.images %q }}`, name)
	})

	src = g.replace(m.src, src, "${SUBSTRATE_VERSION_SUFFIX}", `{{ include "substrate.versionSuffix" . }}`, false)
	src = g.replace(m.src, src, `"${SUBSTRATE_VERSION}"`, `{{ .Values.substrateVersion | quote }}`, false)
	src = g.replace(m.src, src, "${SUBSTRATE_VERSION}", `{{ .Values.substrateVersion }}`, false)
	src = g.replace(m.src, src, "${ENVOY_DATAPLANE_IMAGE}", `{{ index .Values.images "envoy-dataplane" }}`, false)

	switch path.Base(m.src) {
	case "atelet.yaml":
		g.expect(m.src, src, "substrate.versionSuffix")
	case "atenet-egress.yaml":
		src = g.egressFlags(m.src, src)
		g.expect(m.src, src, `"envoy-dataplane"`)
	case "postgres.yaml":
		src = g.postgres(m.src, src)
	}
	if strings.Contains(src, "${") && path.Base(m.src) != "postgres.yaml" {
		g.fail("%s: a ${...} placeholder is left that chartgen does not know: %q", m.src, firstPlaceholder(src))
	}
	if m.wrap != "" {
		src = "{{- if " + m.wrap + " }}\n" + src + "\n{{- end }}\n"
	}
	return src
}

func (g *generator) replace(file, src, old, new string, must bool) string {
	if must && !strings.Contains(src, old) {
		g.fail("%s: expected %q", file, old)
	}
	return strings.ReplaceAll(src, old, new)
}

func (g *generator) expect(file, src, substr string) {
	if !strings.Contains(src, substr) {
		g.fail("%s: expected %q after substitution; has the upstream manifest changed?", file, substr)
	}
}

var placeholder = regexp.MustCompile(`\$\{[A-Z_]+\}`)

func firstPlaceholder(s string) string { return placeholder.FindString(s) }

// egressFlags replaces the #ATE_EGRESS_INJECT_FLAGS marker with the flags
// ate-setup gives the k8s.io credential provider (steps/overlay.go).
func (g *generator) egressFlags(file, src string) string {
	marker := regexp.MustCompile(`(?m)^( *)#ATE_EGRESS_INJECT_FLAGS\b.*$`)
	loc := marker.FindStringSubmatchIndex(src)
	if loc == nil {
		g.fail("%s: no #ATE_EGRESS_INJECT_FLAGS marker", file)
		return src
	}
	indent := src[loc[2]:loc[3]]
	flags := []string{
		"--credential-provider-name=k8s.io",
		"--credential-provider-address=k8s-credential-provider.ate-system.svc:50051",
		"--credential-provider-ca-file=/run/servicedns.podcert.ate.dev/trust-bundle.pem",
		"--credential-provider-client-cert=/run/podidentity.podcert.ate.dev/credential-bundle.pem",
		"--credential-provider-server-name=k8s-credential-provider.ate-system.svc",
	}
	var b strings.Builder
	for i, f := range flags {
		if i > 0 {
			b.WriteString("\n")
		}
		b.WriteString(indent + "- " + f)
	}
	return src[:loc[0]] + b.String() + src[loc[1]:]
}

// postgres has the StatefulSet's postStart hook run setup.sql after it
// creates the database, as ate-setup does over `kubectl exec` once the pod is
// up. The script is idempotent, and pg_hba lets only the local socket in as
// postgres, which is why it runs in the pod.
func (g *generator) postgres(file, src string) string {
	createdb := "                  createdb -U \"${POSTGRES_USER}\" atepg\n                fi\n"
	var sets strings.Builder
	for _, s := range postgresSetup {
		fmt.Fprintf(&sets, " \\\n                  --set=%s=%s", s.name, s.value)
	}
	run := createdb +
		"                psql --no-psqlrc --single-transaction --set=ON_ERROR_STOP=1 -U \"${POSTGRES_USER}\" -d atepg" +
		sets.String() +
		" \\\n                  -f /etc/substrate-setup/setup.sql\n"
	src = g.replace(file, src, createdb, run, true)

	mount := "        - name: data\n          mountPath: /var/lib/postgresql/data\n"
	src = g.replace(file, src, mount, mount+
		"        - name: substrate-setup\n          mountPath: /etc/substrate-setup\n          readOnly: true\n", true)

	volumes := "      volumes:\n"
	if strings.Count(src, volumes) != 1 {
		g.fail("%s: expected one %q", file, strings.TrimSpace(volumes))
	}
	return strings.Replace(src, volumes, volumes+
		"      - name: substrate-setup\n        configMap:\n          name: postgres-substrate-setup\n", 1)
}

