// Package chartgen renders Helm charts from the Substrate project's own
// Kubernetes manifests, at the commit the installer pins, so they install
// what `ate-setup deploy ate-system` installs with pre-built images on GKE.
//
// The manifests are copied as they are, with only the substitutions
// ate-setup itself makes (image references, the version and its DaemonSet
// suffix, the egress credential-provider flags) turned into chart values.
// What ate-setup does imperatively becomes, here:
//
//   - CRDs: a chart of their own (substrate-crds), installed first, so a
//     SandboxConfig in the main chart has its type and CRDs still upgrade.
//   - The CA and JWT key pools: Secrets filled from values. Helm cannot
//     produce two of the five key formats, so the caller generates them.
//   - The API server's environment and authentication config: templates.
//   - The bundled Postgres role and schema setup: the project's setup.sql,
//     run from the StatefulSet's existing postStart hook.
//
// Node labels, the micro-VM sandbox (its assets are assembled and staged into
// the bucket, and its SandboxConfig carries their checksums, by
// hack/install-microvm-deps.sh) and the demo's ActorTemplates (API calls to
// ate-api-server) are not things a chart can own, and are left to the caller.
//
// Every substitution is checked: if the upstream manifests stop matching what
// this package expects, Generate fails rather than emitting a chart that
// quietly differs from ate-setup's install.
package chartgen

