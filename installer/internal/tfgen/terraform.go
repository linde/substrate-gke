// ModuleDir is where the generated module lives, relative to the repository
// root.
const ModuleDir = "terraform/modules/substrate-gke"

// GeneratedFiles maps each file the generator owns, relative to the
// repository root, to its contents. Everything else in the module is written
// by hand. substrate is a checkout of the Substrate commit the installer pins
// (see SubstrateTree), which the Helm charts are rendered from; empty leaves
// the charts out.
func GeneratedFiles(substrate string) (map[string][]byte, error) {
	files := map[string][]byte{
		ModuleDir + "/variables.tf": RenderVariables(),
		ModuleDir + "/options.tf":   RenderOptions(),
		ModuleDir + "/defaults.tf":  RenderDefaults(),
		ModuleDir + "/INPUTS.md":    RenderInputsDoc(),
	}
	for name, data := range renderModuleTemplates() {
		files[ModuleDir+"/"+name] = data
	}
	if substrate != "" {
		charts, err := chartgen.Generate(substrate, ChartsDir)
		if err != nil {
			return nil, err
		}
		for name, data := range charts {
			files[name] = data
		}
	}
	return files, nil
}

// ChartsDir is where the generated Helm charts go, inside the module so a
// git source for the module brings them along.
const ChartsDir = ModuleDir + "/charts"

// OwnedDirs are directories (relative to the repository root) the generator
// owns outright: any file in them it did not generate is stale.
var OwnedDirs = []string{ChartsDir}

// SubstrateTree returns a checkout of the Substrate commit the installer
// pins, fetching it into the user cache the first time.
func SubstrateTree(ctx context.Context) (string, error) {
	cache, err := os.UserCacheDir()
	if err != nil {
		return "", err
	}
	dir := filepath.Join(cache, "substrate-gke", "tfgen-substrate-"+snapshot.ShortCommit())
	if _, err := os.Stat(filepath.Join(dir, snapshot.CompleteMarker)); err == nil {
		return dir, nil
	}
	if err := os.RemoveAll(dir); err != nil {
		return "", err
	}
	return dir, snapshot.FetchTree(ctx, dir, "")
}

const header = "Code generated by installer/cmd/tfgen from installer/internal/inputs; DO NOT EDIT.\n" +
	"Edit the declarations in installer/internal/inputs and run `make generate`;\n" +
	"see " + ModuleDir + "/README.md for how the module is generated and kept in sync."

func writeHeader(b *bytes.Buffer) {
	for _, line := range strings.Split(header, "\n") {
		b.WriteString("# " + line + "\n")
	}
}

// ref is the expression for an input in the module.
func ref(name string) string { return "var." + name }

func tfType(k inputs.Kind) string {
	switch k {
	case inputs.Int:
		return "number"
	case inputs.Bool:
		return "bool"
	}
	return "string"
}

// customHCL are the HCL conditions of inputs' custom checks, with {self} for
// the input's expression. Every name in inputs.CustomChecks needs one
// (TestEveryCustomCheckHasHCL).
var customHCL = map[string]string{
	inputs.CheckImageVersionLength: fmt.Sprintf(`length(split("@", {self})[0]) <= %d`, inputs.LabelValueMaxLength),
	inputs.CheckImageVersionLabel:  fmt.Sprintf(`can(regex(%s, split("@", {self})[0]))`, hclString(inputs.LabelValuePattern)),
	// Mirrors gcp's atLeastMinor: the major and minor are the first two
	// dot-separated fields, each read with strconv.Atoi (so a sign is
	// allowed); anything that does not read that way, fewer than two fields
	// included, lands in try's fallback and passes. (HCL's || does not
	// short-circuit, hence try.)
	inputs.CheckSupportedRelease: fmt.Sprintf(`try(
      !can(regex(%[1]s, split(".", {self})[0])) ||
      !can(regex(%[1]s, split(".", {self})[1])) ||
      tonumber(trimprefix(split(".", {self})[0], "+")) > %[2]d ||
      (tonumber(trimprefix(split(".", {self})[0], "+")) == %[2]d &&
      tonumber(trimprefix(split(".", {self})[1], "+")) >= %[3]d),
      true
    )`, hclString(`^[+-]?[0-9]+$`), gcp.MinSupportedRelease.Major, gcp.MinSupportedRelease.Minor),
	inputs.CheckReleaseChannel: `contains(["", "rapid", "regular", "stable", "extended"], lower({self}))`,
	inputs.CheckNotExtended:    `lower({self}) != "extended"`,
}

// condition is r's HCL condition for input in.
func condition(in *inputs.Input, r inputs.Rule) string {
	self := ref(in.Name)
	var c string
	switch r.Kind {
	case inputs.MaxLength:
		c = fmt.Sprintf("length(%s) <= %d", self, r.Max)
	case inputs.Whole:
		c = fmt.Sprintf("floor(%s) == %s", self, self)
	case inputs.Required:
		c = fmt.Sprintf(`trimspace(%s) != ""`, self)
	case inputs.Matches:
		c = fmt.Sprintf(`%s == "" || can(regex(%s, %s))`, self, hclString(r.Pattern), self)
	case inputs.OneOf:
		quoted := make([]string, len(r.Choices))
		for i, choice := range r.Choices {
			quoted[i] = hclString(choice)
		}
		c = fmt.Sprintf("contains([%s], %s)", strings.Join(quoted, ", "), self)
	case inputs.IntBetween:
		c = fmt.Sprintf("%s >= %d && %s <= %d", self, r.Min, self, r.Max)
	case inputs.IntAtLeastMaxOf:
		c = fmt.Sprintf("%s >= max(%s, %d)", self, ref(r.Other), r.Min)
	case inputs.Custom:
		h, ok := customHCL[r.Check]
		if !ok {
			panic("tfgen: no HCL for custom check " + strconv.Quote(r.Check))
		}
		c = strings.ReplaceAll(h, "{self}", self)
	default:
		panic(fmt.Sprintf("tfgen: no HCL for rule kind %d", r.Kind))
	}
	if r.When != nil {
		c = fmt.Sprintf("%s != %s || (%s)", ref(r.When.Name), hclLiteral(r.When.Value), c)
	}
	return c
}

// references are the inputs r's condition reads besides in itself.
func references(in *inputs.Input, r inputs.Rule) []string {
	var out []string
	if r.Kind == inputs.IntAtLeastMaxOf {
		out = append(out, r.Other)
	}
	if r.When != nil {
		out = append(out, r.When.Name)
	}
	return out
}

// message is r's message as an HCL string, its placeholders interpolated.
func message(in *inputs.Input, r inputs.Rule) string {
	self := ref(in.Name)
	escaped := hclEscape(r.Message)
	return `"` + strings.NewReplacer(
		inputs.PlaceholderValue, "${"+self+"}",
		inputs.PlaceholderQuoted, "${jsonencode("+self+")}",
		inputs.PlaceholderVersion, `${jsonencode(split("@", `+self+`)[0])}`,
	).Replace(escaped) + `"`
}

// RenderVariables renders variables.tf: a variable per input, a validation
// block per rule.
func RenderVariables() []byte {
	var b bytes.Buffer
	writeHeader(&b)
	var screen state.Step = -1
	for _, in := range inputs.All {
		if in.Screen != screen {
			screen = in.Screen
			fmt.Fprintf(&b, "\n# ─── Wizard step: %s %s\n", screen.Title(), strings.Repeat("─", max(3, 56-len(screen.Title()))))
		}
		b.WriteString("\n")
		fmt.Fprintf(&b, "variable %q {\n", in.Name)
		fmt.Fprintf(&b, "  description = %s\n", hclString(describe(in)))
		fmt.Fprintf(&b, "  type        = %s\n", tfType(in.Kind))
		if in.Default != nil {
			fmt.Fprintf(&b, "  default     = %s\n", hclLiteral(in.Default))
		}
		b.WriteString("  nullable    = false\n")
		for _, r := range in.AllRules() {
			cond := condition(in, r)
			b.WriteString("\n  validation {\n")
			// terraform fmt aligns the = signs only of single-line
			// attributes.
			if strings.Contains(cond, "\n") {
				fmt.Fprintf(&b, "    condition = %s\n", cond)
			} else {
				fmt.Fprintf(&b, "    condition     = %s\n", cond)
			}
			fmt.Fprintf(&b, "    error_message = %s\n", message(in, r))
			b.WriteString("  }\n")
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

// RenderDefaults renders defaults.tf: every input's default as a local, so
// the module's own HCL can say "cleared means the default" without restating
// a value that would then go stale.
func RenderDefaults() []byte {
	var b bytes.Buffer
	writeHeader(&b)
	b.WriteString("\nlocals {\n  defaults = {\n")
	width := 0
	for _, in := range inputs.All {
		if in.Default != nil {
			width = max(width, len(in.Name))
		}
	}
	for _, in := range inputs.All {
		if in.Default != nil {
			fmt.Fprintf(&b, "    %-*s = %s\n", width, in.Name, hclLiteral(in.Default))
		}
	}
	b.WriteString("  }\n\n")
	b.WriteString("  # Values the module takes from the installer.\n")
	width = 0
	for _, c := range constants() {
		width = max(width, len(c.name))
	}
	for _, c := range constants() {
		fmt.Fprintf(&b, "  %-*s = %s\n", width, c.name, hclString(c.value))
	}
	b.WriteString("}\n")
	return b.Bytes()
}

// RenderOptions renders options.tf: the module's Terraform-only settings.
func RenderOptions() []byte {
	var b bytes.Buffer
	writeHeader(&b)
	b.WriteString("#\n# Terraform-only settings: how the module behaves, not wizard inputs.\n")
	for _, o := range Options {
		b.WriteString("\n")
		fmt.Fprintf(&b, "variable %q {\n", o.Name)
		fmt.Fprintf(&b, "  description = %s\n", hclString(o.Description))
		fmt.Fprintf(&b, "  type        = %s\n", tfType(o.Kind))
		fmt.Fprintf(&b, "  default     = %s\n", hclLiteral(o.Default))
		b.WriteString("  nullable    = false\n")
		b.WriteString("}\n")
	}
	return b.Bytes()
}

func describe(in *inputs.Input) string {
	return fmt.Sprintf("%s (Wizard: %s › %s.)", in.Description, in.Screen.Title(), in.Label)
}

// hclString quotes s as an HCL string literal, escaping template sequences
// so it is taken literally.
func hclString(s string) string { return `"` + hclEscape(s) + `"` }

func hclEscape(s string) string {
	q := strconv.Quote(s)
	q = q[1 : len(q)-1]
	q = strings.ReplaceAll(q, "${", "$${")
	q = strings.ReplaceAll(q, "%{", "%%{")
	return q
}

// hclLiteral renders a default or condition value as an HCL literal.
func hclLiteral(v any) string {
	switch x := v.(type) {
	case string:
		return hclString(x)
	case bool:
		return strconv.FormatBool(x)
	case int:
		return strconv.Itoa(x)
	}
	panic(fmt.Sprintf("tfgen: no HCL literal for %T", v))
}

// RenderInputsDoc renders INPUTS.md: the inputs as a table, by wizard step.
func RenderInputsDoc() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "<!-- %s -->\n\n", strings.ReplaceAll(header, "\n", " "))
	b.WriteString("# Inputs\n\n")
	b.WriteString("Every variable is a value the installer wizard asks for, validated by the same rules.\n")
	var screen state.Step = -1
	for _, in := range inputs.All {
		if in.Screen != screen {
			screen = in.Screen
			fmt.Fprintf(&b, "\n## %s\n\n", screen.Title())
			b.WriteString("| Variable | Type | Default | Wizard field | Rejected when |\n")
			b.WriteString("|---|---|---|---|---|\n")
		}
		def := "*required*"
		if in.Default != nil {
			def = "`" + mdEscape(hclLiteral(in.Default)) + "`"
		}
		var rules []string
		for _, r := range in.AllRules() {
			msg := strings.NewReplacer(
				inputs.PlaceholderValue, "*value*",
				inputs.PlaceholderQuoted, "*value*",
				inputs.PlaceholderVersion, "*version*",
			).Replace(r.Message)
			if r.When != nil {
				msg = fmt.Sprintf("(when `%s = %s`) %s", r.When.Name, hclLiteral(r.When.Value), msg)
			}
			rules = append(rules, mdEscape(msg))
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n",
			in.Name, tfType(in.Kind), def, mdEscape(in.Label), strings.Join(rules, "<br>"))
	}
	return b.Bytes()
}

var mdSpecial = regexp.MustCompile(`([|<>])`)

func mdEscape(s string) string { return mdSpecial.ReplaceAllString(s, `\$1`) }
