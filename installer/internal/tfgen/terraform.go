// Package tfgen renders the Terraform module under terraform/ from the
// wizard's input declarations (internal/inputs). Everything Terraform-specific
// lives here: the installer itself neither imports this package nor knows the
// module exists.
//
// Each inputs.RuleKind has an HCL translation below, and each custom check a
// hand-written HCL condition; the conformance test runs the same cases through
// inputs.Validate and `terraform plan` and requires the same verdicts.
package tfgen

